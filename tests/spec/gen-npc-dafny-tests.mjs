// node tests/spec/gen-npc-dafny-tests.mjs [path/to/NpcDialogue.dfy]
// Generates src/ts/process/npcCheck.dafny.test.ts from the Witness* lemmas of the verified spec (default tests/spec/NpcDialogue.dfy,
// a copy of ~/Downloads/architecture-debug/specs/risu-npc-dialogue/NpcDialogue.dfy): each lemma `ensures [!]Accept(<Npc>, Facts(...))`
// becomes one test that the JS mirror accept() agrees with Dafny. Re-run after any change to the .dfy (and re-verify it first).
import fs from 'fs'
import path from 'path'
import { fileURLToPath } from 'url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..")
const src = process.argv[2] ?? path.join(root, 'tests/spec/NpcDialogue.dfy')
const out = path.join(root, 'src/ts/process/npcCheck.dafny.test.ts')
const dfy = fs.readFileSync(src, 'utf8')

const consts = Object.fromEntries([...dfy.matchAll(/^const (\w+): Item := "([^"]+)"/gm)].map((m) => [m[1], m[2]]))
const splitTop = (s) => { const out = []; let d = 0, cur = ''; for (const ch of s) { if ('({['.includes(ch)) d++; if (')}]'.includes(ch)) d--; if (ch === ',' && d === 0) { out.push(cur.trim()); cur = '' } else cur += ch } if (cur.trim()) out.push(cur.trim()); return out }
const set = (s) => { const b = s.trim().replace(/^\{|\}$/g, '').trim(); return b ? splitTop(b).map((x) => { if (!(x in consts)) throw new Error(`unknown item ${x}`); return consts[x] }) : [] }
const map = (s) => { const b = s.trim().replace(/^map\[|\]$/g, '').trim(); return b ? splitTop(b).map((kv) => { const [k, v] = kv.split(':=').map((x) => x.trim()); return [consts[k], Number(v)] }) : [] }
const bool = (s) => { if (s !== 'true' && s !== 'false') throw new Error(`not a bool: ${s}`); return s === 'true' }
function npc(expr) {
    const e = expr.trim()
    let m = /^(\w+)\(\)(?:\.\((\w+) := (-?\d+)\))?$/.exec(e)
    if (m) {
        const body = new RegExp(`function ${m[1]}\\(\\): Npc \\{\\s*(Npc\\([\\s\\S]*?\\))\\s*\\}`).exec(dfy)
        if (!body) throw new Error(`no function ${m[1]}`)
        const base = npc(body[1])
        if (m[2]) base[m[2]] = Number(m[3])
        return base
    }
    m = /^Npc\(([\s\S]*)\)$/.exec(e)
    if (!m) throw new Error(`cannot read Npc ${e}`)
    const a = splitTop(m[1])
    if (a.length !== 7) throw new Error(`Npc arity ${a.length}`)
    return { isAdmin: bool(a[0]), needs: set(a[1]), has: map(a[2]), knows: set(a[3]), trust: Number(a[4]), promises: set(a[5]), received: set(a[6]) }
}
function facts(args) {
    const a = splitTop(args)
    if (a.length !== 10) throw new Error(`Facts arity ${a.length} (the spec changed: update the generator)`)
    return { requests: set(a[0]), offers: set(a[1]), refusals: set(a[2]), handed: set(a[3]), questHook: bool(a[4]), exposition: bool(a[5]), playerAskedWhy: bool(a[6]), reasonFlag: bool(a[7]), sentences: Number(a[8]), unaddressed: bool(a[9]) }
}

const cases = []
for (const m of dfy.matchAll(/lemma (Witness\w+)\(\)\s*\n\s*ensures (!?)Accept\(([\s\S]*?), Facts\(([^\n]*)\)\)\s*\n/g)) {
    cases.push({ name: m[1], accept: m[2] !== '!', npc: npc(m[3]), facts: facts(m[4]) })
}
if (cases.length < 6) throw new Error(`only ${cases.length} witnesses read`)
const accDecl = /predicate Accept[\s\S]*?\n\}/.exec(dfy)[0]

const body = `// GENERATED by scripts/gen-npc-dafny-tests.mjs from tests/spec/NpcDialogue.dfy (${cases.length} Witness lemmas). Do not edit:
// change the .dfy, re-verify it (./tools/dafny --spec risu-npc-dialogue), then re-run the generator.
//
// The Dafny predicate this mirrors:
${accDecl.split('\n').map((l) => '//   ' + l).join('\n')}
import { describe, expect, test } from 'vitest'
// @ts-ignore plain JS module (npcCheck.d.mts)
import { accept } from './npcCheck.mjs'

type Case = { name: string; accept: boolean; npc: { isAdmin: boolean; needs: string[]; has: [string, number][]; knows: string[]; trust: number; promises: string[]; received: string[] }; facts: Record<string, unknown> }
const CASES: Case[] = ${JSON.stringify(cases, null, 4)}

const card = (n: Case['npc']) => ({ ...n, needs: new Set(n.needs), has: new Map(n.has), knows: new Set(n.knows), promises: new Set(n.promises), received: new Set(n.received) })
const fx = (f: Record<string, unknown>): any => ({ ...f, requests: new Set(f.requests as string[]), offers: new Set(f.offers as string[]), refusals: new Set(f.refusals as string[]), handed: new Set(f.handed as string[]) })

describe('npcCheck accept() agrees with the verified Dafny Accept on every Witness lemma', () => {
    for (const c of CASES) {
        test(\`\${c.name}: Dafny says \${c.accept ? 'Accept' : '!Accept'}\`, () => {
            expect(accept(card(c.npc), fx(c.facts)).length === 0).toBe(c.accept)
        })
    }
})
`
fs.writeFileSync(out, body)
console.log(`${path.relative(root, out)}: ${cases.length} cases from ${src}`)
